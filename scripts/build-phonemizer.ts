/**
 * Builds the phonemizer practice speech runs on: `src/shared/speech/phonemizer/`.
 *
 *   node scripts/build-phonemizer.ts
 *
 * Piper voices read phonemes, not letters, and eSpeak NG makes them. The
 * source is the WebAssembly build of piper-phonemize in
 * `@diffusionstudio/piper-wasm` (MIT; eSpeak NG is GPL-3.0, see
 * https://github.com/rhasspy/espeak-ng). Its data package carries every
 * eSpeak language, 18 MB of it the Russian and Chinese dictionaries; this
 * keeps only the dictionaries of the app's languages, about 1 MB, and makes
 * the loader an ES module.
 *
 * The output is committed, so nothing here runs on deploy. Rerun it after
 * adding a language.
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';

/** eSpeak dictionaries to keep, one per language the voices speak. */
const DICTIONARIES = ['de_dict', 'en_dict'];

const source = resolve('node_modules/@diffusionstudio/piper-wasm/build');
const out = resolve('src/shared/speech/phonemizer');

interface PackageFile {
  filename: string;
  start: number;
  end: number;
}

const loader = await readFile(join(source, 'piper_phonemize.js'), 'utf8');
const data = await readFile(join(source, 'piper_phonemize.data'));

const call = loader.match(/loadPackage\((\{"files":.*?"remote_package_size":\d+\})\)/);
if (!call) throw new Error('The loader no longer lists its data files where expected');
const { files } = JSON.parse(call[1]!) as { files: PackageFile[] };

const kept = files.filter(({ filename }) => !filename.endsWith('_dict') || DICTIONARIES.some((name) => filename.endsWith(`/${name}`)));
const missing = DICTIONARIES.filter((name) => !kept.some(({ filename }) => filename.endsWith(`/${name}`)));
if (missing.length > 0) throw new Error(`No ${missing.join(', ')} in the data package`);

let offset = 0;
const parts: Buffer[] = [];
const slim = kept.map(({ filename, start, end }) => {
  parts.push(data.subarray(start, end));
  const file = { filename, start: offset, end: offset + end - start };
  offset = file.end;
  return file;
});
const metadata = JSON.stringify({ files: slim, remote_package_size: offset });

// The CommonJS and AMD exports at the end make way for an ES one.
const tail = loader.lastIndexOf("if (typeof exports === 'object'");
if (tail < 0) throw new Error('The loader no longer ends with its exports where expected');
// Node's modules are only reached when it runs in Node, never in the browser;
// without them, bundlers have nothing to stub.
const browser = loader.slice(0, tail).replace(call[1]!, () => metadata).replace(/require\("(fs|path|crypto)"\)/g, 'undefined');
const module = `${browser}export default createPiperPhonemize;\n`;

await mkdir(out, { recursive: true });
await writeFile(join(out, 'piper_phonemize.js'), `// Generated by scripts/build-phonemizer.ts. Do not edit.\n${module}`);
await writeFile(join(out, 'piper_phonemize.data'), Buffer.concat(parts));
await writeFile(join(out, 'piper_phonemize.wasm'), await readFile(join(source, 'piper_phonemize.wasm')));
console.log(`${kept.length} of ${files.length} files, ${(offset / 1e6).toFixed(2)} MB of ${(data.length / 1e6).toFixed(2)} MB`);
